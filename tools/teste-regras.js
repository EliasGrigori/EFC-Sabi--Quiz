/* Confere as regras do Firebase (docs/firebase-rules.json) com os formatos reais que o Sabiá grava. Usa o avaliador rules-sim.js. */
const fs = require("fs"), SIM = require("./rules-sim.js");
const acha = rel => [__dirname, require("path").join(__dirname, "..")].map(d => require("path").join(d, rel)).find(fs.existsSync);
const regras = JSON.parse(fs.readFileSync(acha("docs/firebase-rules.json"), "utf8"));
const noApp = fs.readFileSync(acha("dist/index.html"), "utf8");
let ok = 0, falha = 0, T = null;
const t = (nome, cond, det) => { if (cond) { ok++; console.log("OK   " + nome); } else { falha++; console.log("FALHA " + nome + (det ? " · " + det : "")); } };
const w = (c, v) => { const r = SIM.gravar(regras, T, c, v); if (r.ok) T = r.arvore; return r; };
const pode = (nome, c, v) => { const r = w(c, v); t("Aceita: " + nome, r.ok, r.motivo); };
const nega = (nome, c, v) => { const antes = JSON.stringify(T), r = w(c, v); t("Recusa: " + nome, !r.ok && JSON.stringify(T) === antes, r.ok ? "foi aceito" : ""); };
const S = "/salas/482915";
T = null;
t("As regras do app são as do arquivo docs/firebase-rules.json", (() => { const m = noApp.match(/const REGRAS_FIREBASE = `([\s\S]*?)`;/); return m && JSON.stringify(JSON.parse(m[1])) === JSON.stringify(regras); })());
pode("instrutor publica a sala", S + "/pub", {meta: {sid: "a"}, fase: {etapa: "espera", idx: -1}, item: null});
pode("instrutor publica resultados", S + "/res", {p1: {tot: 10, np: 3}});
pode("celular entra na sala", S + "/part/p1", {n: "Maria Souza", c: 2, s: "Ordenha", t: Date.now()});
pode("celular entra sem setor e sem cor", S + "/part/p9", {n: "Zé", s: "", t: 1});
nega("entrada sem nome", S + "/part/p2", {c: 1, t: 1});
nega("nome com mais de 60 letras", S + "/part/p2", {n: "x".repeat(61)});
nega("campo desconhecido na entrada", S + "/part/p2", {n: "Ana", hack: "x"});
nega("campo desconhecido solto na pessoa", S + "/part/p1/hack", "x");
nega("cor fora do intervalo", S + "/part/p1/c", 99);
pode("reforço refeito (tentativa 1, errou)", S + "/part/p1/ref/0", {t: 1, ok: 0});
pode("reforço refeito (tentativa 3, acertou)", S + "/part/p1/ref/0", {t: 3, ok: 1});
nega("reforço com 9 tentativas", S + "/part/p1/ref/1", {t: 9, ok: 0});
nega("reforço com ok diferente de 0 e 1", S + "/part/p1/ref/1", {t: 1, ok: 5});
nega("reforço sem ok", S + "/part/p1/ref/1", {t: 1});
nega("reforço com campo a mais", S + "/part/p1/ref/1", {t: 1, ok: 0, x: "a"});
pode("comentário do participante", S + "/part/p1/com/abc123", {k: "sugestao", x: "O telão ficou ótimo", t: Date.now()});
nega("comentário com mais de 300 letras", S + "/part/p1/com/zzz", {k: "sugestao", x: "a".repeat(301), t: 1});
nega("comentário sem texto", S + "/part/p1/com/zzz", {k: "sugestao", t: 1});
nega("comentário com campo a mais", S + "/part/p1/com/zzz", {k: "sugestao", x: "oi", t: 1, extra: 1});
pode("resposta do instrutor ao comentário", S + "/part/p1/rsp/abc123", {x: "Obrigado, vamos melhorar"});
nega("resposta do instrutor com mais de 300 letras", S + "/part/p1/rsp/zzz", {x: "a".repeat(301)});
nega("resposta do instrutor com campo a mais", S + "/part/p1/rsp/zzz", {x: "oi", y: 1});
pode("resposta à pergunta, primeira vez", S + "/resp/p1/0", {r: 2});
nega("trocar a resposta já enviada", S + "/resp/p1/0", {r: 3});
pode("apagar a resposta (instrutor reabre)", S + "/resp/p1/0", null);
pode("assinatura, primeira vez", S + "/ass/p1", "data:image/jpeg;base64,AAAA");
nega("assinatura gigante", S + "/ass/p2", "x".repeat(40001));
nega("assinatura trocada", S + "/ass/p1", "data:image/jpeg;base64,BBBB");
pode("participante sai da sala", S + "/part/p9", null);
/* selos */
const COD = "SAB-1A2B-3C4D-5E6F-0A1B-2C3D";
pode("carimbo de tempo do servidor", "/selos/" + COD, {t: {".sv": "timestamp"}});
nega("carimbar de novo o mesmo código", "/selos/" + COD, {t: {".sv": "timestamp"}});
nega("carimbo com horário escolhido à mão", "/selos/SAB-1111-2222-3333-4444-5555", {t: 1600000000000});
nega("carimbo com código inválido", "/selos/qualquer-coisa", {t: {".sv": "timestamp"}});
nega("carimbo com letras fora de A-F", "/selos/SAB-1A2B-3C4D-5E6F-0A1B-2C3Z", {t: {".sv": "timestamp"}});
nega("carimbo com campo a mais", "/selos/SAB-AAAA-BBBB-CCCC-DDDD-EEEE", {t: {".sv": "timestamp"}, nota: "oi"});
nega("apagar um carimbo", "/selos/" + COD, null);
t("O carimbo gravado tem um horário recente", T && T.selos && T.selos[COD] && Math.abs(T.selos[COD].t - Date.now()) < 5000);
/* leitura */
t("Qualquer um lê uma sala pela chave", SIM.podeLer(regras, S + "/pub", T));
t("Ninguém lista todas as salas", !SIM.podeLer(regras, "/salas", T));
t("Ninguém lista os carimbos", !SIM.podeLer(regras, "/selos", T));
t("Lê o carimbo de um código", SIM.podeLer(regras, "/selos/" + COD, T));
t("Ninguém lê a raiz", !SIM.podeLer(regras, "/", T));
const r = w("/qualquer", "x"); t("Gravar fora de salas e selos é recusado", !r.ok);
console.log("\n" + ok + " OK / " + falha + " FALHAS"); process.exit(falha ? 1 : 0);
